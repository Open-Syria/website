"""Reviewed Arabic normalization shared by academic announcements 8 and 9."""
import re
from domestic import clean


def clean_foreign(value):
    # Announcement 8 uses two font maps, distinct from the domestic tables.
    fixes = {
        'التقائن': 'التقاني', 'التقابن': 'التقاني', 'التقائ': 'التقاني', 'التقاب': 'التقاني',
        'عير ن': 'عين', 'عي ن': 'عين', 'الفير نياء': 'الفيزياء', 'فير نيائ': 'فيزيائ',
        'الإنكلير نية': 'الإنكليزية', 'الإنكلي نية': 'الإنكليزية',
        'االنكلير نية': 'الإنكليزية', 'اإلنكلير نية': 'الإنكليزية',
        'اإلنكلي نية': 'الإنكليزية', 'االنكلي نية': 'الإنكليزية',
        'وظيفن ي': 'وظيفي', 'التجهير نات': 'التجهيزات', 'الثائن': 'الثاني', 'الثابن': 'الثاني',
        'القانوئن': 'القانوني', 'القانوبن': 'القانوني', 'التلفزيوئن': 'التلفزيوني',
        'التلفزيوبن': 'التلفزيوني', 'ملي نم': 'ملتزم', 'فتن ي': 'فني', 'الدوام فن': 'الدوام في',
        'ابير ن': 'أبين', 'ابي ن': 'أبين', 'السفي ة': 'السفيرة', 'عربي ن': 'عربين',
        'عربير ن': 'عربين', 'سلقي ن': 'سلقين', 'سلقير ن': 'سلقين',
        'الي امج': 'البرامج', 'اإلحصائ': 'الإحصائي', 'الحسة': 'الحسكة',
        'تقويم الكالم': 'تقويم الكلام', 'اأطراف': 'الأطراف',
        'التحليل المخبر ي': 'التحليل المخبري', 'علم المرآة': 'علم المرأة',
        'الاثانية': 'الثانية', 'الاديان': 'الأديان', 'واصوله': 'وأصوله',
    }
    for source, target in fixes.items(): value = value.replace(source, target)
    value = re.sub(r'(?<!\w)عالج(?!\w)', 'علاج', value)
    value = clean(value)
    value = value.replace('( ن الإحصاء الرياضي', '( الإحصاء الرياضي')
    value = value.replace('الإحصائيي', 'الإحصائي').replace('ي العلاج الفيزيائ', 'العلاج الفيزيائ')
    value = value.replace('ي الإخراج', 'الإخراج')
    for source, target in {'اأطراف': 'الأطراف', 'التحليل المخبر ي': 'التحليل المخبري',
                           'الاديان': 'الأديان', 'الاثانية': 'الثانية',
                           'ي حمص الدوام في': 'الدوام في حمص'}.items():
        value = value.replace(source, target)
    value = re.sub(r'الإحصائ(?!\w)', 'الإحصائي', value)
    value = re.sub(r'الفيزيائ(?!\w)', 'الفيزيائي', value)
    value = re.sub(r'^ي (.*?) التقاني$', r'المعهد التقاني \1', value)
    return value
