def normalize(text):
    # Fix known character-map artifacts, preserving all names, branches and conditions.
    text=text.replace('ـ','')
    for a,b in FIXES.items(): text=text.replace(a,b)
    text=text.replace('الالت','الآلات').replace('الالذقية','اللاذقية')
    for a,b in [('اال','الا'),('اإل','الإ'),('األ','الأ'),('اآل','الآ')]:text=text.replace(a,b)
    text=text.replace('التقانى','التقاني').replace('المعهدالتقان','المعهد التقان')
    m=re.match(r'^ي (.*?)المعهد التقاني?(.*)$',text)
    if m:text='المعهد التقاني '+m.group(1).strip()+m.group(2)
    text=re.sub(r'^ي (.*?)التقاني(.*)$',r'المعهد التقاني \1\2',text)
    text=text.replace('العلوم(ى ','العلوم(').replace('العلوم(ي ','العلوم(')
    text=text.replace('المتقدمينن','المتقدمين').replace('المتقدميني','المتقدمين')
    text=text.replace('المعهد التقاني الزراع','المعهد التقاني الزراعي')
    text=text.replace('الزراعيي','الزراعي').replace('الاحصائي','الإحصائي')
    text=text.replace('ي العلاج الفيزيائي','العلاج الفيزيائي')
    text=text.replace('الإسالم','الإسلام').replace('الإعالم','الإعلام').replace('الاسالم','الإسلام')
    text=text.replace('تجهير ى','تجهيز').replace('عالج وظيفي ي','علاج وظيفي')
    text=text.replace('الآالت','الآلات').replace('لأطراف','للأطراف').replace('( ي الإخراج','( الإخراج')
    text=re.sub(r'\s*([()/])\s*',r' \1 ',text)
    text=re.sub(r'\s*-\s*',' - ',text)
    text=re.sub(r'\s+',' ',text).strip()
    if text=='الهندسة المعلوماتية البرمجيات )':text='الهندسة المعلوماتية ( البرمجيات )'
    return text
